def functions(tree):
    found=[]
    def walk(node, parents):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            found.append(('.'.join(parents+[node.name]),node))
            parents=parents+[node.name]
        elif isinstance(node, ast.ClassDef):
            parents=parents+[node.name]
        for child in ast.iter_child_nodes(node):
            walk(child,parents)
    walk(tree,[])
    return found

def description(qualified,node,module):
    if node.name.startswith('test_') and node.name in DESCRIPTIONS: return DESCRIPTIONS[node.name]
    if node.name.startswith('test_'):
        return 'Проверяет сценарий: ' + node.name[5:].replace('_',' ') + '. Утверждения и ожидаемые ошибки приведены в исходнике теста.'
    if node.name in ('setUp','tearDown'):
        return 'Подготавливает окружение теста.' if node.name=='setUp' else 'Освобождает окружение после теста.'
    if node.name=='__init__': return 'Инициализирует экземпляр '+qualified.rsplit('.',1)[0]+' и его состояние; для окон создаёт элементы и обработчики интерфейса.'
    if node.name=='main': return 'Точка запуска модуля '+module+'; связывает его операции в самостоятельный сценарий.'
    if node.name in ('save','add','remove','upsert','start','worker'):
        actions={'save':'Проверяет и сохраняет состояние редактора', 'add':'Добавляет соответствие', 'remove':'Удаляет выбранное соответствие', 'upsert':'Добавляет или обновляет соответствие', 'start':'Проверяет введённые параметры и запускает действие', 'worker':'Выполняет фоновую часть операции, передавая результат и ошибки в интерфейс'}
        return actions[node.name]+' в контексте `'+qualified.rsplit('.',1)[0]+'`.'
    if node.name.startswith('_set_') and node.name.endswith('_busy'):return 'Блокирует или восстанавливает связанные кнопки на время соответствующей операции.'
    if node.name=='log' and module=='task_sync_gui.py':return 'Передаёт сообщение в главный поток Tkinter через after.'
    if node.name in DESCRIPTIONS:return DESCRIPTIONS[node.name]
    doc=ast.get_docstring(node)
    if doc:return ' '.join(doc.split())
    if module.startswith('test_'):return 'Вспомогательная функция теста: подготавливает данные или имитирует зависимость для проверяемого сценария.'
    print(f"MISSING {module}:{qualified}")
    return "ТРЕБУЕТ ОПИСАНИЯ"

